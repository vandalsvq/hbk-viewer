# Реквизит с основным объектом есть только у формы внешней обработки.
ОБЪЕКТ_XML = '''\t\t<Attribute name="Объект" id="1">
\t\t\t<Type>
\t\t\t\t<v8:Type>cfg:ExternalDataProcessorObject.%(name)s</v8:Type>
\t\t\t</Type>
\t\t\t<MainAttribute>true</MainAttribute>
\t\t</Attribute>
'''


def логформа(имя_обработки=None):
    """XML формы из form_layout.xml. Без имени обработки - вариант без основного реквизита."""
    объект = "" if имя_обработки is None else ОБЪЕКТ_XML % {"name": имя_обработки}
    return читать("form_layout.xml") % {"объект": объект}


def модуль_формы(дополнительные=()):
    """Склейка модуля формы.

    Директивы у частей разные: интерфейс несёт свои, разбор и иконки идут на клиент,
    файловая часть - на сервер без контекста.

    Структура модуля - по стандарту 1С (std455): области первого уровня задаёт
    form_ui.bsl, а части движка подставляются внутрь его области служебных процедур
    подобластями по смыслу. Вне областей в модуле не должно остаться ни строки.

    Параметры:
      дополнительные - последовательность пар (файл, имя подобласти).
    """
    части = [("РазборПакета", с_директивами(читать("engine_client.bsl"))),
             ("ЧтениеФайлов", с_директивами(читать("engine_data.bsl"),
                                            "&НаКлиентеНаСервереБезКонтекста", снять_экспорт=True)),
             ("Иконки", с_директивами(читать("icons.bsl")))]
    for имя, область in дополнительные:
        части.append((область, с_директивами(читать(имя))))

    движок = "\n\n".join(в_области(область, текст) for область, текст in части)

    интерфейс = читать("form_ui.bsl")
    if МАРКЕР_ДВИЖКА not in интерфейс:
        raise SystemExit("в form_ui.bsl нет строки-маркера %r - некуда ставить движок"
                         % МАРКЕР_ДВИЖКА)
    return интерфейс.replace(МАРКЕР_ДВИЖКА, движок)


def в_области(имя, текст):
    return "#Область %s\n\n%s\n\n#КонецОбласти" % (имя, без_разделов_модуля(текст).strip("\n"))


# Разделы модуля по стандарту: в отдельном файле они на месте, а внутри формы дают
# второй "программный интерфейс" и вложенные "служебные процедуры" внутри служебных.
РАЗДЕЛЫ_МОДУЛЯ = ("ПрограммныйИнтерфейс", "СлужебныйПрограммныйИнтерфейс",
                  "СлужебныеПроцедурыИФункции")


def без_разделов_модуля(текст):
    """Снимает внешние разделы модуля, оставляя их содержимое и смысловые подобласти."""
    результат = []
    стек = []
    for строка in текст.replace("\r\n", "\n").split("\n"):
        голая = строка.strip()
        if голая.startswith("#Область "):
            снимаем = not стек and голая[len("#Область "):].strip() in РАЗДЕЛЫ_МОДУЛЯ
            стек.append(снимаем)
            if снимаем:
                continue
        elif голая.startswith("#КонецОбласти"):
            if стек and стек.pop():
                continue
        результат.append(строка)
    return "\n".join(результат)


def читать(имя):
    """Читает файл из исходников обработки, а если его там нет - из каталога стендов."""
    for каталог in (ИСХОДНИКИ, TOOLS):
        путь = os.path.join(каталог, имя)
        if os.path.exists(путь):
            return open(путь, encoding="utf-8-sig").read()

    raise SystemExit("не найден файл %s ни в src, ни в tools" % имя)


def с_директивами(текст, директива="&НаКлиенте", снять_экспорт=False):
    """Проставляет директиву перед каждым методом файла.

    Экспорт в модуле формы имеет смысл только у клиентских методов: серверные с ним
    не компилируются, поэтому у файловой части он снимается. Вне формы (общий модуль
    стенда) файлы берутся как есть, вместе с Экспорт.
    """
    строки = текст.replace("\r\n", "\n").split("\n")
    результат = []
    for строка in строки:
        if re.match(r"^(Функция|Процедура)\s", строка):
            результат.append(директива)
            if снять_экспорт:
                строка = re.sub(r"\s+Экспорт\s*$", "", строка)
        результат.append(строка)
    return "\n".join(результат)


def записать(путь, текст):
    os.makedirs(os.path.dirname(путь), exist_ok=True)
    with open(путь, "wb") as f:
        f.write(b"\xef\xbb\xbf" + текст.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8"))
